#!/usr/bin/env python3
"""Write Gw444/Colourings.lean: three good exact colourings of [1, 328] for (k, l) = (4, 4).

The colourings are those of the proof of Theorem 444(a) in Quantavane's paper "Power-residue
colourings and exact Gallai-van der Waerden numbers" (November 2026). Let p = 109, m = 3, and for
a not divisible by p let cls(a) = a^36 mod 109, the cubic residue class of a (one of three cube
roots of unity modulo 109; 109 = 1 mod 3). Colour X in [1, 328] with X != 1 (mod 109) by its class
cls(X - 1), numbered 0 (the cubes), 1, 2. The four points X = 1 + 109 k (k = 0, 1, 2, 3, that is
X = 1, 110, 219, 328) get the colour z(k):
  r = 4: z = (0, 3, 3, 0)  (the points 1 and 328 get the class of the cubes, 110 and 219 a fourth colour);
  r = 5: z = (3, 4, 3, 4);
  r = 6: z = (3, 4, 5, 3).
This script recomputes the colourings, checks them by brute force (every colour occurs; no rainbow
and no monochromatic 4-term progression in [1, 328]), compares the 4-colouring with the file
colouring_1_328.txt of the public data (up to renaming of colours, if the file is given), and writes
each colouring as a natural number in base 8 (point x gets the digit x - 1), with kernel checks on\npieces of the range of differences.

Nothing here is trusted by the Lean proof: Lean's kernel checks the colourings it is given.

Usage: make_colourings.py OUT.lean [colouring_1_328.txt]
"""
import sys

P, M, N = 109, 3, 328


def cls(a):
    return pow(a % P, (P - 1) // M, P)


ORDER = [1] + sorted({cls(a) for a in range(1, P)} - {1})
NAME = {v: i for i, v in enumerate(ORDER)}
Z = {4: (0, 3, 3, 0), 5: (3, 4, 3, 4), 6: (3, 4, 5, 3)}


def colouring(r):
    return [Z[r][(x - 1) // P] if (x - 1) % P == 0 else NAME[cls(x - 1)] for x in range(1, N + 1)]


def bad(c, k, l):
    n, out = len(c), 0
    for d in range(1, n):
        for x in range(1, n + 1):
            if x + (k - 1) * d <= n and len({c[x + i * d - 1] for i in range(k)}) == k:
                out += 1
            if x + (l - 1) * d <= n and len({c[x + i * d - 1] for i in range(l)}) == 1:
                out += 1
    return out


MAXW = 3000   # progressions (start points) per kernel check


def chunks(n, m, D, maxw):
    """Split the differences 1..D into consecutive pieces (lo, count) of at most maxw start points."""
    out, lo = [], 1
    while lo <= D:
        c = w = 0
        while lo + c <= D and (c == 0 or w + n - (m - 1) * (lo + c) <= maxw):
            w += n - (m - 1) * (lo + c)
            c += 1
        out.append((lo, c))
        lo += c
    return out


def canon(c):
    m = {}
    return [m.setdefault(v, len(m)) for v in c]


def main():
    out = sys.argv[1]
    cols = {}
    for r in (4, 5, 6):
        c = colouring(r)
        assert sorted(set(c)) == list(range(r)), r
        assert bad(c, 4, 4) == 0, r
        cols[r] = c
    if len(sys.argv) > 2:
        f = [int(ch) for ch in open(sys.argv[2]).read().strip()]
        assert canon(f) == canon(cols[4]), 'colouring_1_328.txt differs'
        print('colouring_1_328.txt: the same 4-colouring up to renaming')
    with open(out, 'w') as f:
        f.write('module\n\npublic import Gw444.Check\n\n@[expose] public section\n\n')
        f.write('/-!\n# Three good exact colourings of `[1, 328]` (generated by `scripts/make_colourings.py`)\n\n')
        f.write('Point `x` gets the base-8 digit `x - 1` of the constant (`digitCol`). With `p = 109`, a point\n')
        f.write('`X ≢ 1 (mod 109)` has colour `0`, `1` or `2` according to the cubic residue class of `X - 1`\n')
        f.write('(`(X - 1)^36 mod 109` is `1`, `' + str(ORDER[1]) + '` or `' + str(ORDER[2]) + '`); the points ')
        f.write('`1, 110, 219, 328` have the colours\n')
        f.write('`0, 3, 3, 0` (`r = 4`), `3, 4, 3, 4` (`r = 5`) and `3, 4, 5, 3` (`r = 6`). The colour classes have\n')
        for r in (4, 5, 6):
            f.write(f'{", ".join(str(cols[r].count(t)) for t in range(r))} points (`r = {r}`)' +
                    (';\n' if r < 6 else '.\n'))
        f.write('\nPoint 1 first:\n\n')
        for r in (4, 5, 6):
            s = ''.join(map(str, cols[r]))
            f.write(f'* `r = {r}`:\n  `{s[:82]}`\n  `{s[82:164]}`\n  `{s[164:246]}`\n  `{s[246:]}`\n')
        f.write('\nEach is checked by `decide +kernel` (no `native_decide`): `allCols` (every colour occurs) and\n')
        f.write('`rangeTest` (every progression) on pieces of the range of differences, which `good_of_tests`\n')
        f.write('puts together.\n-/\n\n')
        f.write('namespace Gw444\n\n')
        m, D = 4, N // 3
        assert (m - 1) * (D + 1) > N
        for r in (4, 5, 6):
            B = sum(v << (3 * i) for i, v in enumerate(cols[r]))
            assert all(((B >> (3 * (x - 1))) % 8) % r == cols[r][x - 1] for x in range(1, N + 1))
            f.write(f'/-- The {r}-colouring as a number in base 8 (point `x` is digit `x - 1`). -/\n')
            f.write(f'def B{r} : ℕ :=\n  {hex(B)}\n\n')
            f.write(f'/-- The good exact {r}-colouring of `[1, 328]`. -/\n')
            f.write(f'def col{r} : ℕ → Fin {r} := digitCol {r} (by decide) B{r}\n\n')
            f.write(f'theorem cols{r} : allCols {r} B{r} 328 {r} = true := by decide +kernel\n\n')
            pieces = chunks(N, m, D, MAXW)
            for j, (lo, c) in enumerate(pieces):
                f.write(f'theorem rows{r}_{j} : rangeTest {r} B{r} 4 4 328 4 {lo} {c} = true := by decide +kernel\n\n')
            f.write(f'theorem good{r} : IsGoodExactColouring {r} 4 4 328 col{r} :=\n')
            f.write(f'  good_of_tests (m := 4) (D := {D}) (by decide) (by decide) (by decide) (by decide) (by decide) cols{r} (by\n')
            f.write('    intro d h1 h2\n')
            for j, (lo, c) in enumerate(pieces):
                if j < len(pieces) - 1:
                    f.write(f'    by_cases c{j} : d < {lo + c}\n')
                    f.write(f'    · exact rangeTest_spec _ rows{r}_{j} d (by omega) (by omega)\n')
                else:
                    f.write(f'    exact rangeTest_spec _ rows{r}_{j} d (by omega) (by omega))\n\n')
        f.write('end Gw444\n')
    print('wrote', out)


if __name__ == '__main__':
    main()
